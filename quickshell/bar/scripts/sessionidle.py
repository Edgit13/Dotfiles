#!/usr/bin/env python3
"""Edots idle/session manager.

Settings → System → Session writes ~/.config/quickshell/session.json.  This
helper turns that file into a swayidle configuration, reloads the swayidle
user service, and exposes the session actions (lock / suspend / …).

Usage:
  sessionidle.py apply [--force]     regenerate swayidle.conf and reload
  sessionidle.py status              show the effective timers
  sessionidle.py lock                lock the screen
  sessionidle.py suspend             lock (optional) then suspend
  sessionidle.py logout|reboot|poweroff
"""
from __future__ import annotations

import argparse
import json
import os
import shlex
import shutil
import subprocess
import sys
import time
from pathlib import Path

HOME = Path.home()
CONFIG = HOME / ".config"
SESSION_JSON = CONFIG / "quickshell" / "session.json"
SWAYIDLE_CONF = CONFIG / "mango" / "swayidle.conf"
SHELL_QML = CONFIG / "quickshell" / "bar" / "shell.qml"
LOCK_SCRIPT = CONFIG / "quickshell" / "bar" / "lockscreen" / "lock.sh"
SELF = Path(__file__).resolve()
UNIT = "swayidle.service"

DEFAULTS = {
    "idleEnabled": True,
    "lockMinutes": 5,
    "screenOffMinutes": 10,
    "suspendMinutes": 0,
    "lockOnSuspend": True,
}

LIMITS = {
    "lockMinutes": (0, 120),
    "screenOffMinutes": (0, 120),
    "suspendMinutes": (0, 240),
}


# ───────────────────────────── config ─────────────────────────────
def _clamp_int(value, key) -> int:
    lo, hi = LIMITS[key]
    try:
        number = int(round(float(value)))
    except (TypeError, ValueError):
        number = int(DEFAULTS[key])
    return max(lo, min(hi, number))


def load() -> dict:
    data = dict(DEFAULTS)
    try:
        raw = json.loads(SESSION_JSON.read_text(encoding="utf-8"))
        if isinstance(raw, dict):
            data.update(raw)
    except (OSError, ValueError):
        pass

    for key in LIMITS:
        data[key] = _clamp_int(data.get(key), key)
    data["idleEnabled"] = bool(data.get("idleEnabled", True))
    data["lockOnSuspend"] = bool(data.get("lockOnSuspend", True))
    return data


def has_wlopm() -> bool:
    return shutil.which("wlopm") is not None


def render(cfg: dict) -> str:
    lines = [
        "# Automatically generated by sessionidle.py — do not edit by hand.",
        "# Change it in Settings → System → Session, or run: edots session apply",
        "",
    ]
    lock_cmd = f"bash {shlex.quote(str(LOCK_SCRIPT))}"
    suspend_cmd = f"python3 {shlex.quote(str(SELF))} suspend"

    if cfg["idleEnabled"]:
        lock = cfg["lockMinutes"] * 60
        screen = cfg["screenOffMinutes"] * 60
        suspend = cfg["suspendMinutes"] * 60

        if lock > 0:
            lines.append(f"timeout {lock} {lock_cmd}")
        if screen > 0 and has_wlopm():
            lines.append(
                f'timeout {screen} wlopm --off "*" resume wlopm --on "*"'
            )
        elif screen > 0:
            lines.append("# Display-off timeout skipped: install wlopm to enable it.")
        if suspend > 0:
            lines.append(f"timeout {suspend} {suspend_cmd}")
    else:
        lines.append("# Idle timeouts are disabled in Settings → System → Session.")

    if cfg["lockOnSuspend"]:
        lines += ["", f"before-sleep {lock_cmd}"]
    if has_wlopm():
        lines.append('after-resume wlopm --on "*"')
    lines.append("")
    return "\n".join(lines)


def write_atomic(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


# ───────────────────────────── service ─────────────────────────────
def systemctl(*args: str) -> int:
    return subprocess.run(
        ["systemctl", "--user", *args],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    ).returncode


def unit_available() -> bool:
    return systemctl("cat", UNIT) == 0


def service_active() -> bool:
    return systemctl("is-active", "--quiet", UNIT) == 0


def spawn_direct():
    subprocess.run(["pkill", "-x", "swayidle"],
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    subprocess.Popen(
        ["swayidle", "-w", "-C", str(SWAYIDLE_CONF)],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        start_new_session=True,
    )


def apply(force: bool = False) -> int:
    cfg = load()
    text = render(cfg)

    try:
        changed = SWAYIDLE_CONF.read_text(encoding="utf-8") != text
    except OSError:
        changed = True
    if changed:
        write_atomic(SWAYIDLE_CONF, text)

    if unit_available():
        systemctl("enable", UNIT)
        if changed or force or not service_active():
            systemctl("restart", UNIT)
    elif changed or force:
        spawn_direct()

    print("swayidle.conf updated" if changed else "swayidle.conf already current")
    return 0


# ───────────────────────────── actions ─────────────────────────────
def run_lock():
    if not LOCK_SCRIPT.is_file():
        print(f"lock script not found: {LOCK_SCRIPT}", file=sys.stderr)
        return 1
    return subprocess.run(["bash", str(LOCK_SCRIPT)]).returncode


def session_locked() -> bool:
    sid = os.environ.get("XDG_SESSION_ID", "")
    if not sid:
        return False
    try:
        value = subprocess.check_output(
            ["loginctl", "show-session", sid, "-p", "LockedHint", "--value"],
            text=True, stderr=subprocess.DEVNULL,
        ).strip()
        return value == "yes"
    except (OSError, subprocess.CalledProcessError):
        return False


def do_lock(cfg: dict) -> int:
    return run_lock()


def do_suspend(cfg: dict) -> int:
    if cfg["lockOnSuspend"]:
        subprocess.Popen(
            ["bash", str(LOCK_SCRIPT)],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        for _ in range(30):
            if session_locked():
                break
            time.sleep(0.1)

    return subprocess.run(["systemctl", "suspend"]).returncode


def status(cfg: dict) -> int:
    def minutes(value: int) -> str:
        return "never" if value <= 0 else f"{value} min"

    active = service_active() if unit_available() else bool(
        subprocess.run(["pgrep", "-x", "swayidle"],
                       stdout=subprocess.DEVNULL).returncode == 0
    )
    screen = minutes(cfg["screenOffMinutes"])
    if cfg["screenOffMinutes"] > 0 and not has_wlopm():
        screen += "  (wlopm missing — disabled)"

    print(f"Idle timeouts   {'on' if cfg['idleEnabled'] else 'off'}")
    print(f"Lock after      {minutes(cfg['lockMinutes'])}")
    print(f"Display off     {screen if cfg['idleEnabled'] else 'never'}")
    print(f"Suspend after   {minutes(cfg['suspendMinutes']) if cfg['idleEnabled'] else 'never'}")
    print(f"Lock on suspend {'yes' if cfg['lockOnSuspend'] else 'no'}")
    print(f"Service         {'active' if active else 'stopped'}")
    print(f"Config          {SWAYIDLE_CONF}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "action", nargs="?", default="status",
        choices=["apply", "status", "lock", "suspend", "logout",
                 "reboot", "poweroff", "pause", "resume"],
    )
    parser.add_argument("--force", action="store_true", help="restart even if the config is unchanged")
    args = parser.parse_args()

    cfg = load()

    if args.action == "apply":
        return apply(force=args.force)
    if args.action == "status":
        return status(cfg)
    if args.action == "lock":
        return do_lock(cfg)
    if args.action == "suspend":
        return do_suspend(cfg)
    if args.action == "logout":
        return subprocess.run(["loginctl", "terminate-user", os.environ.get("USER", "")]).returncode
    if args.action == "reboot":
        return subprocess.run(["systemctl", "reboot"]).returncode
    if args.action == "poweroff":
        return subprocess.run(["systemctl", "poweroff"]).returncode
    if args.action == "pause":
        return subprocess.run(["pkill", "-STOP", "-x", "swayidle"]).returncode
    if args.action == "resume":
        return subprocess.run(["pkill", "-CONT", "-x", "swayidle"]).returncode
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
